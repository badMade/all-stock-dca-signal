"""Tests for ``scripts/verify_perplexity_pair.py``.

On 2026-10-14 the 9:55 backup task ran an earlier planner and prompt pair than the one the operator believed they had
pasted: the Instructions box and the project Files copy of ``backup_planner.pyz`` are edited by hand in two places and
nothing checked that they agree. The planner does check its own stamp at run time (step 0), but only after a slot has
fired. This tool checks the pair BEFORE it is pasted, from files on the operator's own machine.

Written from the required behavior, not from the implementation:

* A set agrees when every prompt's stamp equals the planner's ``content_sha256`` and every prompt's universe hash and
  symbol count equal what the planner itself reports.
* Anything else fails closed (exit 2) and names the file and the check, never a private value.
* It only reads: it never edits the planner or a prompt, and never prints a filled-in value (last four, email).
"""

from __future__ import annotations

import json
import zipapp
from pathlib import Path

from scripts import verify_perplexity_pair as vp

ROOT = Path(__file__).resolve().parents[2]
REAL_PROMPTS = ROOT / "claude" / "dca-executor-prompts" / "perplexity"

BUILD = "a" * 64
OTHER_BUILD = "b" * 64
UNIVERSE = "c" * 64
OTHER_UNIVERSE = "d" * 64
COUNT = 67

_MAIN = """
import json, sys
BUILD, UNIVERSE, COUNT = {build!r}, {universe!r}, {count!r}
if "--build-info" in sys.argv:
    print(json.dumps({{"content_sha256": BUILD, "source_commit": "0" * 40}}))
elif sys.argv[1:2] == ["universe"]:
    print(json.dumps({{"status": "OK", "count": COUNT, "universe_hash": UNIVERSE, "symbols": []}}))
else:
    sys.exit(3)
"""

PROMPT = """STANDING BACKUP EXECUTOR - slot {slot}
Task {task}. Fires 09:55 ET on trading days.
Generated by scripts/generate_perplexity_backup_prompts.py from repo config. Universe hash {universe} ({count} symbols). Market calendar retrieved 2026-07-28.
Its content_sha256 must equal {build} exactly; if it differs, place NOTHING.
{extra}
"""


def _planner(tmp_path, *, build=BUILD, universe=UNIVERSE, count=COUNT, name="backup_planner.pyz") -> Path:
    src = tmp_path / f"src_{name}"
    src.mkdir()
    (src / "__main__.py").write_text(_MAIN.format(build=build, universe=universe, count=count), encoding="utf-8")
    target = tmp_path / name
    zipapp.create_archive(src, target)
    return target


def _prompts(tmp_path, *, build=BUILD, universe=UNIVERSE, count=COUNT, extra="", slots=("0935", "1030")) -> Path:
    folder = tmp_path / "prompts"
    folder.mkdir(exist_ok=True)
    for slot in slots:
        text = PROMPT.format(slot=slot, task="aaaa1111", universe=universe, count=count, build=build, extra=extra)
        (folder / f"{slot}-backup.txt").write_text(text, encoding="utf-8")
    return folder


def _run(planner, prompts, capsys):
    code = vp.main(["--planner", str(planner), "--prompts", str(prompts)])
    out = capsys.readouterr()
    return code, out.out + out.err


# -- agreeing sets -----------------------------------------------------------------------------------------------


def test_a_matching_set_passes_and_says_so_per_file(tmp_path, capsys):
    code, text = _run(_planner(tmp_path), _prompts(tmp_path), capsys)
    assert code == 0
    assert "0935-backup.txt" in text and "1030-backup.txt" in text
    assert "OK" in text and "MISMATCH" not in text


# -- every way a pair can disagree --------------------------------------------------------------------------------


def test_a_prompt_stamped_for_a_different_planner_build_fails(tmp_path, capsys):
    """The 2026-10-12 and 2026-10-14 failure: prompt and attached planner were different builds."""
    code, text = _run(_planner(tmp_path), _prompts(tmp_path, build=OTHER_BUILD), capsys)
    assert code == 2
    assert "MISMATCH" in text and "stamp" in text
    assert BUILD[:8] in text and OTHER_BUILD[:8] in text  # short hashes only, enough to tell the builds apart


def test_a_prompt_with_an_older_universe_than_the_planner_fails(tmp_path, capsys):
    """APH and TEL added to config: the planner lists them, the older prompt header does not."""
    code, text = _run(_planner(tmp_path), _prompts(tmp_path, universe=OTHER_UNIVERSE), capsys)
    assert code == 2
    assert "universe" in text.lower() and "MISMATCH" in text


def test_a_different_symbol_count_fails(tmp_path, capsys):
    code, text = _run(_planner(tmp_path), _prompts(tmp_path, count=65), capsys)
    assert code == 2
    assert "symbols" in text.lower() and "MISMATCH" in text


def test_one_stale_prompt_among_good_ones_is_named(tmp_path, capsys):
    planner = _planner(tmp_path)
    folder = _prompts(tmp_path, slots=("0935", "1030", "1130"))
    stale = folder / "1130-backup.txt"
    stale.write_text(stale.read_text(encoding="utf-8").replace(BUILD, OTHER_BUILD), encoding="utf-8")
    code, text = _run(planner, folder, capsys)
    assert code == 2
    flagged = [line for line in text.splitlines() if "MISMATCH" in line]
    assert len(flagged) == 1 and "1130-backup.txt" in flagged[0]


def test_an_unfilled_placeholder_fails(tmp_path, capsys):
    """A repo copy pasted straight into Perplexity still carries ${...} placeholders and would fail the account rule."""
    code, text = _run(_planner(tmp_path), _prompts(tmp_path, extra="ends in ${ROBINHOOD_AGENTIC_ACCOUNT_LAST4}"), capsys)
    assert code == 2
    assert "placeholder" in text.lower()
    assert "ROBINHOOD_AGENTIC_ACCOUNT_LAST4" in text  # the variable NAME is not private


def test_a_prompt_with_no_stamp_or_universe_line_fails(tmp_path, capsys):
    planner = _planner(tmp_path)
    folder = _prompts(tmp_path)
    (folder / "0935-backup.txt").write_text("STANDING BACKUP EXECUTOR - slot 0935\nno stamp here\n", encoding="utf-8")
    code, text = _run(planner, folder, capsys)
    assert code == 2
    assert "0935-backup.txt" in text


# -- fail closed on the inputs themselves ---------------------------------------------------------------------------


def test_no_prompts_in_the_folder_is_an_error(tmp_path, capsys):
    empty = tmp_path / "empty"
    empty.mkdir()
    code, text = _run(_planner(tmp_path), empty, capsys)
    assert code == 2 and "no" in text.lower()


def test_a_missing_planner_file_is_an_error_not_a_traceback(tmp_path, capsys):
    code, text = _run(tmp_path / "absent.pyz", _prompts(tmp_path), capsys)
    assert code == 2
    assert "Traceback" not in text


def test_a_planner_that_does_not_run_is_an_error(tmp_path, capsys):
    broken = tmp_path / "backup_planner.pyz"
    broken.write_bytes(b"not a zip archive")
    code, text = _run(broken, _prompts(tmp_path), capsys)
    assert code == 2
    assert "Traceback" not in text


def test_a_planner_that_prints_something_other_than_json_is_an_error(tmp_path, capsys):
    src = tmp_path / "junk_src"
    src.mkdir()
    (src / "__main__.py").write_text("print('hello')\n", encoding="utf-8")
    junk = tmp_path / "backup_planner.pyz"
    zipapp.create_archive(src, junk)
    code, text = _run(junk, _prompts(tmp_path), capsys)
    assert code == 2


def test_a_stamp_with_an_extra_hex_digit_after_the_hash_fails(tmp_path, capsys):
    """Step 0 demands exact equality, so 65 hex digits must not be read as the 64-digit hash plus nothing."""
    planner = _planner(tmp_path)
    folder = _prompts(tmp_path)
    prompt = folder / "0935-backup.txt"
    prompt.write_text(prompt.read_text(encoding="utf-8").replace(f"equal {BUILD} exactly", f"equal {BUILD}f exactly"),
                      encoding="utf-8")
    code, text = _run(planner, folder, capsys)
    assert code == 2 and "0935-backup.txt" in text


def _planner_printing(tmp_path, body: str) -> Path:
    src = tmp_path / "bytes_src"
    src.mkdir()
    (src / "__main__.py").write_text(body, encoding="utf-8")
    target = tmp_path / "backup_planner.pyz"
    zipapp.create_archive(src, target)
    return target


def test_undecodable_planner_stdout_is_a_sanitized_error_not_a_traceback(tmp_path, capsys):
    planner = _planner_printing(tmp_path, "import sys\nsys.stdout.buffer.write(b'\\xff\\xfe not utf-8')\n")
    code, text = _run(planner, _prompts(tmp_path), capsys)
    assert code == 2
    assert "Traceback" not in text and "UnicodeDecodeError" not in text.split("planner:")[0]


def test_undecodable_planner_stderr_does_not_break_a_good_run(tmp_path, capsys):
    body = _MAIN.format(build=BUILD, universe=UNIVERSE, count=COUNT) + "\nimport sys\nsys.stderr.buffer.write(b'\\xff warn')\n"
    code, text = _run(_planner_printing(tmp_path, body), _prompts(tmp_path), capsys)
    assert code == 0, text


# -- read-only and no private values ---------------------------------------------------------------------------------


def test_it_never_modifies_the_planner_or_the_prompts(tmp_path, capsys):
    planner = _planner(tmp_path)
    folder = _prompts(tmp_path)
    before = {p: p.read_bytes() for p in [planner, *folder.glob("*.txt")]}
    _run(planner, folder, capsys)
    assert {p: p.read_bytes() for p in before} == before


def test_filled_in_private_values_are_never_printed(tmp_path, capsys):
    secret_last4 = "4321"
    secret_email = "ops@example.test"
    extra = f"must end in {secret_last4}. Email to {secret_email}. State: cron_tracking/uuid-private-0001/run_state.json"
    code, text = _run(_planner(tmp_path), _prompts(tmp_path, extra=extra), capsys)
    assert code == 0
    assert secret_last4 not in text and secret_email not in text and "uuid-private-0001" not in text


def test_a_failure_message_does_not_leak_filled_in_values_either(tmp_path, capsys):
    extra = "must end in 4321. Email to ops@example.test."
    code, text = _run(_planner(tmp_path), _prompts(tmp_path, build=OTHER_BUILD, extra=extra), capsys)
    assert code == 2
    assert "4321" not in text and "ops@example.test" not in text


# -- the real repo -----------------------------------------------------------------------------------------------------


def test_the_committed_prompts_agree_with_a_planner_built_from_this_checkout(tmp_path, capsys):
    """If the generator, config and planner bundle ever drift apart, this fails before an operator pastes anything."""
    from scripts import build_backup_planner

    planner = tmp_path / "backup_planner.pyz"
    assert build_backup_planner.main(["--out", str(planner)]) == 0
    capsys.readouterr()
    # the committed prompts hold ${...} placeholders by design; the verifier's own flag accepts them for this check
    code = vp.main(["--planner", str(planner), "--prompts", str(REAL_PROMPTS), "--allow-placeholders"])
    out = capsys.readouterr()
    assert code == 0, out.out + out.err
    assert json.dumps(out.out)  # printed something readable
