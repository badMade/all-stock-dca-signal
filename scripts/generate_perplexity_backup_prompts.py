#!/usr/bin/env python3
"""Generate the six Perplexity backup-executor prompts (plan-first design).

WHY GENERATED
-------------
Perplexity cannot read this repo, so every hard rule has to be INLINE in each prompt, and the
numbers in those rules (caps, universe, calendar, sizing version) used to be hand-copied prose
that drifted from config. This script renders them from ``config/*.json`` and the runner's own
constants, so a config change shows up as a failing drift test (``--check``) until the prompts
are regenerated and a human repastes them.

The prompts are thin I/O: gates, two broker evidence polls, a Mac-first planner call with
compute fallbacks, then sequential placement of exactly what the planner returned. All sizing
and cap arithmetic lives in ``dca_order_plan`` (see ``docs/adr-plan-first-backup-executor.md``).

The ``scripts.backup_planner`` command the prompts call is documented in
``claude/dca-executor-prompts/perplexity/README.md``. On the Mac it runs from the checkout; in the sandbox it is
the stamped zipapp ``backup_planner.pyz`` built by ``scripts/build_backup_planner.py``.

Which slots take the safety-gate path (raw responses, ``assemble-market-data``, ``compute --market-data``) is
read from ``scripts.backup_planner.GATED_SLOTS`` when the prompts are built, so wiring a slot there and
regenerating is the whole change. Any other slot stays on the quotes path and reports ``shadow_only``.

Usage::

    python3 -m scripts.generate_perplexity_backup_prompts --write   # (re)write the six files
    python3 -m scripts.generate_perplexity_backup_prompts --check   # exit 1 on drift
"""

