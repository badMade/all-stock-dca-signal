#!/usr/bin/env python3
"""Generate the six Perplexity backup-executor prompts (plan-first design).

WHY GENERATED
-------------
Perplexity cannot read this repo, so the short pasted prompt checks the public slot-status signal
and verifies the stamped planner before requesting its procedure. The planner serves the hard rules
and preflight in part 0; the numbers in those rules (caps, universe, calendar, sizing version) are
rendered from ``config/*.json`` and the runner's own constants.

The prompts are thin I/O: gates, two broker evidence polls, a Mac-first planner call with
compute fallbacks, then sequential placement of exactly what the planner returned. Since PR #1667 the
first plan source is the plan-first recommendation (the Mac's store, or the copy published to the
``recommendations`` branch / Notion), and the planner's ``classify`` recognises Claude's plan-first
orders by the broker order ids its reader saved, since they carry no ``dca-runner-`` reference. All sizing
and cap arithmetic lives in ``dca_order_plan`` (see ``docs/adr-plan-first-backup-executor.md``).

The ``scripts.backup_planner`` command the prompts call is documented in
``claude/dca-executor-prompts/perplexity/README.md``. On the Mac it runs from the checkout; in the sandbox it is
the stamped zipapp ``backup_planner.pyz`` built by ``scripts/build_backup_planner.py``.

Which slots take the safety-gate path (raw responses, ``assemble-market-data``, ``compute --market-data``) is
read from ``scripts.backup_planner.GATED_SLOTS`` when the prompts are built, so wiring a slot there and
regenerating is the whole change. Any other slot stays on the quotes path and reports ``shadow_only``.

Usage::

    python3 -m scripts.generate_perplexity_backup_prompts --write   # (re)write the six files
    python3 -m scripts.generate_perplexity_backup_prompts --check   # exit 1 on drift
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

from scripts import backup_procedure, build_backup_planner, slot_status
from scripts.backup_procedure import BACKUPS, Backup

GITHUB_REPOSITORY = backup_procedure.GITHUB_REPOSITORY  # re-exported: tests and docs name it here
DEFAULT_OUT_DIR = Path(__file__).resolve().parents[1] / "claude" / "dca-executor-prompts" / "perplexity"
# 2026-11-04: a STEP A stand-down writes no state record, so the operator had no status to give
# scripts/backup_cost_ledger.py and the fire landed in "unrecorded". The run now names the ledger status in its last
# reply line instead: no tool call, no file, a few output tokens. The word is the ledger's own vocabulary.
STAND_DOWN_STATUS = "stood_down_signal"
STAND_DOWN_REPLY = f"RESULT: {STAND_DOWN_STATUS}"

_SHORT_PROMPT = """\
STANDING BACKUP EXECUTOR @@TITLE@@
Task @@TASK_ID@@. Fires @@FIRES@@ ET on trading days. Backs up the Claude @@SLOT_LINE@@.
Latest placement: @@LATEST@@ ET.
Generated by scripts/generate_perplexity_backup_prompts.py from repo config. Do not hand-edit; regenerate and repaste.
Sizing version @@LADDER@@. Universe hash @@UNIVERSE_HASH@@ (@@N@@ symbols). Market calendar retrieved @@CAL_RETRIEVED@@.
RUN VALUES (filled in when this prompt is pasted):
   PPLX_RUN_STATE_DIR (the run-state folder for this task): ${PPLX_RUN_STATE_DIR}
   DCA_ALERT_EMAIL_ADDRESS (where step 9 sends alerts): ${DCA_ALERT_EMAIL_ADDRESS}
   ROBINHOOD_AGENTIC_ACCOUNT_LAST4 (the last four digits rule 2 requires): ${ROBINHOOD_AGENTIC_ACCOUNT_LAST4}
   PPLX_PROJECT_FILES_DIR (the folder holding backup_planner.pyz, this task's project files): ${PPLX_PROJECT_FILES_DIR}

STEP A - SIGNAL CHECK
Read @@RAW_URL@@ once, without any other tool call. It is the public @@GITHUB_REPOSITORY@@ branch "@@BRANCH@@" file `slot_status.json`; expect this schema: {"schema": "slot_status/1", "trading_day": "YYYY-MM-DD", "market": "open" or "closed", "updated_at": "...", "slots": {"0935": {"status": "in_progress", "stamped_at": "..."}}}.
Use the current date and clock in America/New_York. This task backs up @@SLOT_LINE@@; @@SLOT_FROM_CLOCK@@. Stand down only when "schema" is "slot_status/1", the trading_day is today, and either "market" is "closed" or today's entry for this task's slot has a nonempty "stamped_at" and "status" is "succeeded". On either result, make no Robinhood call, place nothing, make no other tool call, write no file, send no notification, make your final reply the single line `@@STAND_DOWN_REPLY@@`, and end the run.
If the file cannot be read, is not JSON, has another schema or another day, is malformed, the market is not closed and the slot is in_progress or failed, or there is no entry for this slot, do not stand down: go to STEP B. This signal never authorizes a buy. Read it once and do not retry.

STEP B - PREFLIGHT AND PROCEDURE
The file backup_planner.pyz is attached to this task's project files, in the folder ${PPLX_PROJECT_FILES_DIR}. Run `cd ${PPLX_PROJECT_FILES_DIR}` first. Do not search the file system for the file: if the file is missing or the command fails, place NOTHING, record failed_unexpected_error, notify, and stop without running any other planner command. Run this once (never pass --now), and do not run it again or any other planner command before it:
   python3 backup_planner.pyz preflight --task @@TASK_ID@@
It prints one JSON document: the step 1 gates fields (status, slot, latest_placement_et, now_et) and "build" with content_sha256 and source_commit. A non-zero exit, output that is not that JSON document, or any status other than PROCEED, skipped_market_closed or skipped_outside_window: place NOTHING, record failed_unexpected_error, notify, and stop.
Status skipped_market_closed or skipped_outside_window: stop with exactly that status, here. Make no account lookup, no broker call and no device listing, request no procedure part, and send no notification. Write one JSON state record to ${PPLX_RUN_STATE_DIR}/run_state_<YYYYMMDD>_<HHMM>ET.json (create directories as needed) with: trading_day, slot (null when preflight has none), task_id, fired_at_et, preflight_at_et (its now_et), planner_build (its build), universe_hash and mac_status null, sizing_version @@LADDER@@, status, run_origin scheduled_backup, account_last4 and plan_source null, and executor_orders, orders_planned, orders_placed, skipped and errors as []. Never include the account number. Then end the run.
Status PROCEED: its build.content_sha256 must equal @@BUILD_STAMP@@ exactly; if it differs, take the same fail-closed action (place NOTHING, record failed_unexpected_error, notify, and stop without running any other planner command). The source_commit is recorded but not compared.
Only after that check, fetch part 0:
   python3 backup_planner.pyz procedure --task @@TASK_ID@@ --part 0
It must begin with `PROCEDURE FOR TASK @@TASK_ID@@ - PART 0 OF 3` and end with its matching `END OF PART 0 OF 3 FOR TASK @@TASK_ID@@` line. If it does not print, exits non-zero, or either line is missing or names another task, place NOTHING, record failed_unexpected_error, notify, and stop. Read part 0 completely before doing anything it describes. Part 1 requires the token printed at the end of part 0. No broker or Mac tool is named in this prompt."""


def _build_stamp() -> str:
    """The content hash the sandbox file must report; fail closed if it is not a lowercase sha256."""
    stamp = build_backup_planner.content_sha256()
    if not re.fullmatch(r"[0-9a-f]{64}", stamp):
        raise ValueError("planner content_sha256 is not a lowercase 64-hex digest; refusing to render an unverifiable prompt")
    return stamp


def build_prompts(config_dir: Path | None = None) -> dict[str, str]:
    """The full reference prompts (short prompt + parts 0-3), deterministic and too long to paste."""
    common = backup_procedure.common_values(config_dir)
    settings = slot_status.load_settings(config_dir)
    prompts = {}
    for backup in BACKUPS:
        short = _render_short_prompt(backup, common, settings)
        part0 = backup_procedure.render_part(backup.task_id, 0, directory=config_dir)
        procedure = backup_procedure.render_procedure(backup, common)
        prompts[backup.file] = f"{short.rstrip()}\n\n{part0.rstrip()}\n\n{procedure}"
    return prompts


def _render_short_prompt(backup: Backup, common: dict[str, str], settings: dict) -> str:
    if len(backup.slots) == 1:
        slot_from_clock = f'the slot is "{backup.slots[0]}"'
    else:
        slot_from_clock = 'before 14:30 ET the slot is "1330"; from 14:30 ET the slot is "1430"'
    values = {
        **backup_procedure.backup_values(backup, common),
        "@@RAW_URL@@": slot_status.raw_url(settings["branch"], settings["repository"]),
        "@@BRANCH@@": settings["branch"],
        "@@GITHUB_REPOSITORY@@": settings["repository"],
        "@@SLOT_FROM_CLOCK@@": slot_from_clock,
        "@@BUILD_STAMP@@": _build_stamp(),
        "@@STAND_DOWN_REPLY@@": STAND_DOWN_REPLY,
    }
    text = backup_procedure.substitute(_SHORT_PROMPT, values)
    assert "@@" not in text, backup.file
    return text.rstrip("\n") + "\n"


def build_instructions(config_dir: Path | None = None) -> dict[str, str]:
    """The six short prompts to paste: the slot-status check and pointer to the stamped procedure."""
    common = backup_procedure.common_values(config_dir)
    settings = slot_status.load_settings(config_dir)
    return {backup.file: _render_short_prompt(backup, common, settings) for backup in BACKUPS}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="Write the six prompt files.")
    mode.add_argument("--check", action="store_true", help="Exit 1 if any committed prompt differs from the generator.")
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR)
    args = parser.parse_args(argv)
    prompts = build_instructions()
    if args.write:
        args.out_dir.mkdir(parents=True, exist_ok=True)
        for name, text in prompts.items():
            (args.out_dir / name).write_text(text, encoding="utf-8")
        print(f"wrote {len(prompts)} prompts to {args.out_dir}")
        return 0
    drifted = [
        name for name, text in prompts.items()
        if not (args.out_dir / name).is_file() or (args.out_dir / name).read_text(encoding="utf-8") != text
    ]
    for name in drifted:
        print(f"DRIFT: {name}", file=sys.stderr)
    return 1 if drifted else 0


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main())
