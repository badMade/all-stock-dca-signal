#!/usr/bin/env python3
"""Record Wondrous Octopus Tier C recovery multipliers to the sizing-suggestion history.

This script reads next-day forecast predictions generated by the Wondrous Octopus
multi-quantile neural forecaster (trained on Apple Silicon MPS with conformal prediction
intervals), detects Tier C dip-recovery signals across the active DCA universe, and APPENDS
the bounded multipliers to the append-only ``octopus`` stream of
``sizing_suggestion_history`` (``<cron root>/sizing_suggestions/octopus/<YYYY>.jsonl``).

It deliberately does NOT write ``config/ml_sizing_adjustment.json``: that file feeds live
sizing (``dca_config.load_ml_sizing_adjustment`` -> ``graded_buy_multiplier``), and sizing is
still being determined by comparing several independent suggesters over time. Promoting any
suggester's numbers into live sizing is a deliberate human decision after that review, not
a side effect of this script (see ``docs/sizing_suggestion_history.md``).
"""

from __future__ import annotations

import argparse
import csv
import json
import logging
import sys
from datetime import date, datetime, timezone
from pathlib import Path
from typing import Any, Dict, Set, Tuple

# Repo imports
REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from sizing_suggestion_history import record_suggestions  # noqa: E402

logger = logging.getLogger("publish_octopus_sizing")

DEFAULT_FORECASTS_PATH = REPO_ROOT / "analysis" / "real-octopus-run" / "all_shards_tomorrow.csv"
DEFAULT_METRICS_PATH = REPO_ROOT / "analysis" / "real-octopus-run" / "octopus_validation_metrics.json"
DEFAULT_TICKERS_PATH = REPO_ROOT / "config" / "tickers.json"

DEFAULT_MIN_MULTIPLIER = 0.8
DEFAULT_MAX_MULTIPLIER = 1.4
DEFAULT_TIER_C_MULTIPLIER = 1.25
# Calendar days the newest forecast ``origin_date`` may trail the run date. 5 covers a normal
# weekend plus a market holiday (Fri forecast read on Tue after a Monday holiday is 4); a CSV
# older than that is a stale file being re-run, which would otherwise be recorded with a fresh
# ``recorded_at`` and look like a new forecast in the history (Codex review of cc098ed3, medium).
DEFAULT_MAX_ORIGIN_AGE_DAYS = 5
MODEL_VERSION = "wondrous-octopus-v1-mps"


def load_active_universe(tickers_json_path: Path) -> Set[str]:
    """Load the set of active ticker symbols from tickers.json."""
    if not tickers_json_path.exists():
        logger.warning("Tickers file %s does not exist; returning empty universe", tickers_json_path)
        return set()
    try:
        with open(tickers_json_path, "r", encoding="utf-8") as f:
            data = json.load(f)
        active = data.get("active", [])
        return {str(t).strip().upper() for t in active if t}
    except Exception as exc:
        logger.error("Failed to load active universe from %s: %s", tickers_json_path, exc)
        return set()


def evaluate_tier_c_candidates(
    forecasts_csv_path: Path,
    active_tickers: Set[str],
    *,
    base_tier_c_multiplier: float = DEFAULT_TIER_C_MULTIPLIER,
    max_multiplier: float = DEFAULT_MAX_MULTIPLIER,
) -> Tuple[Dict[str, float], Dict[str, Any]]:
    """Scan next-day predictions for active universe tickers meeting Tier C recovery conditions.

    Tier C recovery logic:
      A dip or pullback where the Octopus conformal upper bound (P90) indicates an upside
      recovery target of > 1.5% and either the expected return is not severely compromised
      (pred_return > -2%) or significant downward variance is already priced (P10 < -1%).

    Args:
        forecasts_csv_path: Path to all_shards_tomorrow.csv.
        active_tickers: Set of active symbols to consider.
        base_tier_c_multiplier: Standard multiplier for Tier C activations.
        max_multiplier: Upper bound ceiling for multiplier.

    Returns:
        Tuple of (adjustments_dict, metadata_dict).
    """
    if not forecasts_csv_path.exists():
        raise FileNotFoundError(f"Forecasts CSV not found: {forecasts_csv_path}")

    adjustments: Dict[str, float] = {}
    tier_c_records: list[dict[str, Any]] = []
    scanned_active = 0

    with open(forecasts_csv_path, "r", encoding="utf-8", newline="") as f:
        reader = csv.reader(f)
        try:
            header = next(reader)

            def _find_all_indices(col_names):
                return [header.index(name) for name in col_names if name in header]

            ticker_indices = _find_all_indices(["ticker"])
            ref_indices = _find_all_indices(["ref_close"])
            p90_indices = _find_all_indices(["close_p90"])
            p10_indices = _find_all_indices(["close_p10"])
            pred_indices = _find_all_indices(["pred_close"])

            if not ticker_indices or not ref_indices or not p90_indices or not p10_indices or not pred_indices:
                return {}, {}

            max_idx = max((ticker_indices + ref_indices + p90_indices + p10_indices + pred_indices) or [-1])
        except StopIteration:
            return {}, {}

        for row in reader:
            if len(row) <= max_idx:
                continue

            ticker = None
            for idx in ticker_indices:
                ticker = row[idx]
                if ticker:
                    break

            ticker = (ticker or "").strip().upper()
            if ticker not in active_tickers:
                continue

            scanned_active += 1
            try:
                ref_close = None
                for idx in ref_indices:
                    try:
                        ref_close = float(row[idx])
                        break
                    except (ValueError, TypeError):
                        pass
                if ref_close is None:
                    continue

                p90_close = None
                for idx in p90_indices:
                    try:
                        p90_close = float(row[idx])
                        break
                    except (ValueError, TypeError):
                        pass
                if p90_close is None:
                    continue

                p10_close = None
                for idx in p10_indices:
                    try:
                        p10_close = float(row[idx])
                        break
                    except (ValueError, TypeError):
                        pass
                if p10_close is None:
                    continue

                pred_close = None
                for idx in pred_indices:
                    try:
                        pred_close = float(row[idx])
                        break
                    except (ValueError, TypeError):
                        pass
                if pred_close is None:
                    continue
            except (KeyError, ValueError, TypeError):
                continue

            if ref_close <= 0 or p90_close <= 0:
                continue

            p90_return = (p90_close - ref_close) / ref_close
            p10_return = (p10_close - ref_close) / ref_close
            pred_return = (pred_close - ref_close) / ref_close

            # Tier C trigger condition
            if p90_return > 0.015 and (pred_return > -0.02 or p10_return < -0.01):
                # Scale multiplier smoothly according to P90 recovery potential
                # Base is 1.25x; additional upside scales up to max_multiplier
                bonus = max(0.0, min(0.15, (p90_return - 0.015) * 1.5))
                multiplier = min(max_multiplier, round(base_tier_c_multiplier + bonus, 4))
                adjustments[ticker] = multiplier
                tier_c_records.append(
                    {
                        "ticker": ticker,
                        "multiplier": multiplier,
                        "p90_return": round(p90_return, 4),
                        "pred_return": round(pred_return, 4),
                        "p10_return": round(p10_return, 4),
                    }
                )

    metadata = {
        "scanned_active_tickers": scanned_active,
        "total_active_universe": len(active_tickers),
        "tier_c_count": len(adjustments),
        "tier_c_sample": tier_c_records[:10],
    }
    return adjustments, metadata


def _source_origin_date(forecasts_csv_path: Path) -> str | None:
    """Latest ``origin_date`` in the forecast CSV, or None when the column is absent.

    Recorded as provenance so a stale ``all_shards_tomorrow.csv`` that is re-run
    later shows up in the history as an old ``origin_date`` against a new
    ``recorded_at``, instead of looking like a fresh forecast.
    """
    with open(forecasts_csv_path, "r", encoding="utf-8", newline="") as f:
        reader = csv.reader(f)
        header = next(reader, None)
        if not header or "origin_date" not in header:
            return None
        idx = header.index("origin_date")
        dates = [row[idx].strip() for row in reader if len(row) > idx and row[idx].strip()]
    return max(dates) if dates else None


def check_source_freshness(
    origin_date: str | None, today: date, max_age_days: int
) -> tuple[bool, str]:
    """Return ``(fresh, reason)``; a missing, unparseable or future-dated origin is not fresh."""
    if not origin_date:
        return False, "forecast CSV has no origin_date column or no dated rows"
    try:
        origin = date.fromisoformat(origin_date)
    except ValueError:
        return False, f"origin_date {origin_date!r} is not an ISO date"
    age = (today - origin).days
    if age < -1:
        # A forecast dated in the future means a bad clock or bad data; do not record it.
        return False, f"origin_date {origin_date} is {-age} days in the future"
    if age > max_age_days:
        return False, f"origin_date {origin_date} is {age} days old (limit {max_age_days})"
    return True, f"origin_date {origin_date} is {age} days old"


def publish_octopus_sizing(
    forecasts_csv: Path,
    tickers_json: Path,
    metrics_path: Path | None = None,
    *,
    min_multiplier: float = DEFAULT_MIN_MULTIPLIER,
    max_multiplier: float = DEFAULT_MAX_MULTIPLIER,
    tier_c_multiplier: float = DEFAULT_TIER_C_MULTIPLIER,
    max_origin_age_days: int = DEFAULT_MAX_ORIGIN_AGE_DAYS,
    history_root: Path | None = None,
    dry_run: bool = False,
    now: datetime | None = None,
) -> Dict[str, Any]:
    """Append Octopus Tier C suggestions to the suggestion history (never to live config).

    Fails closed (``status: stale_source``, nothing recorded) when the forecast CSV's newest
    ``origin_date`` is missing, in the future, or older than ``max_origin_age_days``.
    """
    active_tickers = load_active_universe(tickers_json)
    if not active_tickers:
        return {"status": "failed", "reason": "Active universe is empty or could not be loaded"}

    origin_date = _source_origin_date(forecasts_csv)
    fresh, freshness_reason = check_source_freshness(
        origin_date, (now or datetime.now(timezone.utc)).date(), max_origin_age_days
    )
    if not fresh:
        logger.error("Refusing to record a stale Octopus forecast: %s", freshness_reason)
        return {"status": "stale_source", "reason": freshness_reason, "origin_date": origin_date}

    adjustments, metadata = evaluate_tier_c_candidates(
        forecasts_csv,
        active_tickers,
        base_tier_c_multiplier=tier_c_multiplier,
        max_multiplier=max_multiplier,
    )

    metrics_data = None
    if metrics_path and metrics_path.exists():
        try:
            with open(metrics_path, "r", encoding="utf-8") as f:
                metrics_data = json.load(f)
        except Exception as exc:
            logger.warning("Could not read metrics from %s: %s", metrics_path, exc)

    if dry_run:
        return {
            "status": "dry_run",
            "tier_c_count": len(adjustments),
            "sample_adjustments": dict(list(adjustments.items())[:5]),
            "metadata": metadata,
        }

    metrics = {}
    if metrics_data:
        metrics = {
            key: metrics_data.get(key)
            for key in ("rmse", "mae", "rmse_dollars", "mae_dollars", "device", "model_ready")
        }
    # An empty adjustments dict is still worth recording: "octopus saw no Tier C
    # signal today" is part of the history the comparison needs.
    recorded_path = record_suggestions(
        "octopus",
        adjustments,
        status="published",
        model_version=MODEL_VERSION,
        bounds={"min_multiplier": min_multiplier, "max_multiplier": max_multiplier},
        source={
            "forecasts_csv": forecasts_csv.name,
            "origin_date": origin_date,
            "scanned_active_tickers": metadata.get("scanned_active_tickers"),
            "total_active_universe": metadata.get("total_active_universe"),
            "tier_c_multiplier": tier_c_multiplier,
        },
        metrics=metrics,
        root=history_root,
        now=now,
    )
    return {
        "status": "published",
        "history_file": str(recorded_path),
        "tier_c_count": len(adjustments),
        "active_scanned": metadata.get("scanned_active_tickers"),
        "metadata": metadata,
    }


def main() -> int:
    """CLI entry point for publishing Octopus sizing adjustments."""
    parser = argparse.ArgumentParser(
        description="Record Wondrous Octopus Tier C recovery sizing suggestions to the append-only suggestion history."
    )
    parser.add_argument(
        "--forecasts-csv",
        type=Path,
        default=DEFAULT_FORECASTS_PATH,
        help="Path to all_shards_tomorrow.csv",
    )
    parser.add_argument(
        "--tickers-json",
        type=Path,
        default=DEFAULT_TICKERS_PATH,
        help="Path to config/tickers.json",
    )
    parser.add_argument(
        "--metrics-json",
        type=Path,
        default=DEFAULT_METRICS_PATH,
        help="Path to octopus_validation_metrics.json",
    )
    parser.add_argument(
        "--min-multiplier",
        type=float,
        default=DEFAULT_MIN_MULTIPLIER,
        help="Minimum sizing multiplier bound (schema requires 0.5 <= min <= 1.0)",
    )
    parser.add_argument(
        "--max-multiplier",
        type=float,
        default=DEFAULT_MAX_MULTIPLIER,
        help="Maximum sizing multiplier bound (schema requires 1.0 <= max <= 1.5)",
    )
    parser.add_argument(
        "--tier-c-multiplier",
        type=float,
        default=DEFAULT_TIER_C_MULTIPLIER,
        help="Base multiplier for Tier C recovery signals",
    )
    parser.add_argument(
        "--max-origin-age-days",
        type=int,
        default=DEFAULT_MAX_ORIGIN_AGE_DAYS,
        help="Refuse a forecast CSV whose newest origin_date is older than this many days",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Compute adjustments without writing file",
    )

    args = parser.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")

    result = publish_octopus_sizing(
        args.forecasts_csv,
        args.tickers_json,
        args.metrics_json,
        min_multiplier=args.min_multiplier,
        max_multiplier=args.max_multiplier,
        tier_c_multiplier=args.tier_c_multiplier,
        max_origin_age_days=args.max_origin_age_days,
        dry_run=args.dry_run,
    )

    print(json.dumps(result, indent=2))
    return 0 if result.get("status") in ("published", "dry_run") else 1


if __name__ == "__main__":
    sys.exit(main())
